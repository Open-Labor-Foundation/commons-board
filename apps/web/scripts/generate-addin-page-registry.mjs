#!/usr/bin/env node
/**
 * Regenerates apps/web/lib/addin-page-registry.ts from installed packs'
 * manifests, replacing the old requirement that a developer hand-edit that
 * file per pack. Runs as a `prebuild` script (npm's lifecycle hook fires it
 * automatically before `npm run build`, which is what both the Docker image
 * build and apps/web/entrypoint.sh's rebuild-on-signal path already call).
 *
 * Page components are staged into apps/web/addins/<packId>/pages/ (gitignored,
 * regenerated every run) rather than imported directly from ADDINS_DIR,
 * because ADDINS_DIR is a Docker volume mounted outside the Next.js app's
 * own directory tree -- Next's webpack bundler needs the imported files to
 * be real, resolvable paths inside the project at build time, not an
 * externally-mounted volume path. A pack whose page component file doesn't
 * exist yet at ADDINS_DIR is skipped with a warning, not a failed build --
 * matches installPack()'s same "missing file doesn't break the whole
 * install" behavior (see addin-install.ts).
 */
import { existsSync, mkdirSync, readFileSync, rmSync, statSync, writeFileSync, copyFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const SAFE_ID_PATTERN = /^[a-z0-9][a-z0-9-]*$/;
const SAFE_COMPONENT_PATTERN = /^[A-Za-z][A-Za-z0-9]*$/;

function readJson(filePath) {
  try {
    return JSON.parse(readFileSync(filePath, "utf8"));
  } catch {
    return null;
  }
}

function readInstalledPackIds(addinsDir) {
  const registry = readJson(path.join(addinsDir, "registry.json"));
  const installed = Array.isArray(registry?.installed) ? registry.installed : [];
  return installed.filter((id) => typeof id === "string" && SAFE_ID_PATTERN.test(id));
}

/**
 * Core generation logic, parameterized so it's testable without touching
 * the real ADDINS_DIR/staging/output paths. Returns the generated file
 * content and any per-file warnings; does not write anything itself.
 */
export function generateRegistry(addinsDir, stagingDir) {
  // Fresh staging dir every run -- this is a generated artifact, not source.
  rmSync(stagingDir, { recursive: true, force: true });

  const packIds = readInstalledPackIds(addinsDir);
  const packEntries = [];
  const warnings = [];

  for (const packId of packIds) {
    const manifest = readJson(path.join(addinsDir, packId, "manifest.json"));
    if (!manifest || !Array.isArray(manifest.pages) || manifest.pages.length === 0) continue;

    const routeImports = [];
    for (const page of manifest.pages) {
      const route = typeof page?.route === "string" ? page.route : null;
      const component = typeof page?.component === "string" ? page.component : null;
      if (!route || !component) {
        warnings.push(`${packId}: page entry missing route/component, skipped`);
        continue;
      }
      if (!SAFE_COMPONENT_PATTERN.test(component)) {
        warnings.push(`${packId}: component name "${component}" is not a safe identifier, skipped`);
        continue;
      }

      const sourceFile = path.join(addinsDir, packId, "pages", `${component}.tsx`);
      if (!existsSync(sourceFile) || !statSync(sourceFile).isFile()) {
        warnings.push(`${packId}: pages/${component}.tsx not found at its source, skipped`);
        continue;
      }

      const destDir = path.join(stagingDir, packId, "pages");
      mkdirSync(destDir, { recursive: true });
      copyFileSync(sourceFile, path.join(destDir, `${component}.tsx`));

      routeImports.push({ route, component });
    }

    if (routeImports.length > 0) {
      packEntries.push({ packId, routeImports });
    }
  }

  const lines = [];
  lines.push(`import type { ComponentType } from "react";`);
  lines.push(`import dynamic from "next/dynamic";`);
  lines.push("");
  lines.push("// GENERATED FILE -- do not hand-edit.");
  lines.push("// Regenerated by scripts/generate-addin-page-registry.mjs (a prebuild step) from");
  lines.push("// every installed pack's manifest.json pages[]. Re-run `npm run build` (or trigger");
  lines.push("// a rebuild from the addins UI) after installing or updating a pack.");
  lines.push("");
  lines.push(`export const ADDIN_PAGES: Record<string, Record<string, ComponentType>> = {`);
  for (const { packId, routeImports } of packEntries) {
    lines.push(`  "${packId}": {`);
    for (const { route, component } of routeImports) {
      lines.push(`    "${route}": dynamic(() => import("../addins/${packId}/pages/${component}")),`);
    }
    lines.push(`  },`);
  }
  lines.push(`};`);
  lines.push("");

  const packCount = packEntries.length;
  const pageCount = packEntries.reduce((n, p) => n + p.routeImports.length, 0);
  return { content: lines.join("\n"), warnings, packCount, pageCount };
}

function main() {
  const scriptDir = path.dirname(fileURLToPath(import.meta.url));
  const webRoot = path.resolve(scriptDir, "..");
  const addinsDir = process.env.ADDINS_DIR ?? path.resolve(webRoot, "../../addins");
  const stagingDir = path.join(webRoot, "addins");
  const outputFile = path.join(webRoot, "lib", "addin-page-registry.ts");

  const { content, warnings, packCount, pageCount } = generateRegistry(addinsDir, stagingDir);
  writeFileSync(outputFile, content, "utf8");

  console.log(`[CB] Generated addin-page-registry.ts: ${packCount} pack(s), ${pageCount} page(s).`);
  for (const w of warnings) console.warn(`[CB] ${w}`);
}

// Only auto-run when executed directly (npm run prebuild), not when
// imported by a test.
if (import.meta.url === `file://${process.argv[1]}`) {
  main();
}
